import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { OWNER_ACTIONS } from "@andy/domain";
import { mcpTools } from "./mcp/test-client";
import { fullApp } from "./registry-snapshot";

/**
 * API and MCP reference (AI-146), read from the app as built: every MCP tool (name, first
 * sentence of its description), the owner-only actions (`OWNER_ACTIONS`, AI-19) and every route
 * (method, path, behind the `/api` sign-in or not). Nothing is committed: `pnpm reference` prints it, so two PRs adding a tool or a route
 * never conflict on a list. Who can reach each entry point and how it is authorised stays in
 * `docs/security/`; `reference.test.ts` fails when a route outside the sign-in isn't named there.
 */

export const REGENERATE = "pnpm reference";
const SIGN_IN = "ALL /api/*";

export interface ToolRow {
  name: string;
  summary: string;
}

export interface RouteRow {
  method: string;
  path: string;
  signedIn: boolean;
}

/**
 * A tool's name and the first sentence of its description (a period before a capital ends it),
 * skipping a sentence that only says "Owner only." or "Andy only.".
 */
export function toolRow(tool: { name: string; description: string }): ToolRow {
  const text = tool.description.replace(/\s+/g, " ").trim();
  const sentences = text.split(/(?<=[.!?])\s+(?=[A-Z(`"])/);
  const summary = sentences.find((s) => !/^(?:Andy|owner)[ -]only\.?$/i.test(s)) ?? text;
  return { name: tool.name, summary };
}

/**
 * Routes in registration order (Hono lists one entry per handler), once each. A route is behind
 * the sign-in when it is under `/api/` and registered after the `/api/*` middleware; middleware
 * entries (`ALL …*`) are not routes.
 */
export function routeRows(routes: readonly { method: string; path: string }[]): RouteRow[] {
  const signInAt = routes.findIndex((r) => `${r.method} ${r.path}` === SIGN_IN);
  if (signInAt === -1) throw new Error(`no ${SIGN_IN} middleware: the sign-in boundary moved`);
  const seen = new Set<string>();
  const rows: RouteRow[] = [];
  routes.forEach((r, i) => {
    const key = `${r.method} ${r.path}`;
    if (r.path.endsWith("*") || seen.has(key)) return;
    seen.add(key);
    rows.push({ ...r, signedIn: i > signInAt && r.path.startsWith("/api/") });
  });
  return rows;
}

const cell = (s: string) => s.replace(/\\/g, "\\\\").replace(/\|/g, "\\|");

export function renderReference(tools: ToolRow[], routes: RouteRow[]): string {
  const byPath = [...routes].sort(
    (a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method),
  );
  return [
    `# API and MCP reference (generated by \`${REGENERATE}\`)`,
    "",
    `## MCP tools (${tools.length})`,
    "",
    "| Tool | What it does |",
    "| --- | --- |",
    ...[...tools]
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((t) => `| \`${t.name}\` | ${cell(t.summary)} |`),
    "",
    "## Owner-only actions (`OWNER_ACTIONS` in `packages/domain/src/permissions.ts`)",
    "",
    "Agents and the system get none of these; a tool or route that does one checks `can` (AI-19).",
    "",
    ...Object.entries(OWNER_ACTIONS).map(([key, what]) => `- \`${key}\`: ${what}`),
    "",
    `## Routes (${routes.length})`,
    "",
    "Signed in: Firebase ID token and email allow-list (`/api` middleware). Every other route checks its own caller: who and how in `docs/security/`.",
    "",
    "| Method | Path | Signed in |",
    "| --- | --- | --- |",
    ...byPath.map((r) => `| ${r.method} | \`${r.path}\` | ${r.signedIn ? "yes" : "no"} |`),
  ].join("\n");
}

/** The tools and routes of the app with every optional feature on (fakes only). */
export async function reference(): Promise<{ tools: ToolRow[]; routes: RouteRow[] }> {
  const { app, grants } = fullApp();
  const tools = (await mcpTools(app, grants, "http://localhost/mcp")).map(toolRow);
  return { tools, routes: routeRows(app.routes) };
}

/** An entry point a security doc names: an optional method and a path pattern. */
export interface DocumentedEntry {
  method: string | null;
  pattern: RegExp;
}

const PATH =
  /(?:\b(GET|POST|PUT|PATCH|DELETE|ALL)\s+)?(?<![\w.:/…])(\/[\w.{}:*-]+(?:\/[\w.{}:*-]+)*)/g;

/**
 * Entry points named in the security docs' entry-point tables: any cell of a row in a table whose
 * first header is "Entry point". Prose, risks and other tables don't count. `{id}` and `:id`
 * match one segment; `*` matches within one segment, or anything when it ends the path
 * (`/.well-known/oauth-*`); a path needs at least one literal segment, so `/*` or `/{id}` can't
 * cover every route.
 */
export function documentedEntries(dir: string): DocumentedEntry[] {
  const entries: DocumentedEntry[] = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".md"))) {
    let inEntryTable = false;
    for (const line of readFileSync(join(dir, file), "utf8").split("\n")) {
      if (!line.startsWith("|")) {
        inEntryTable = false;
        continue;
      }
      const firstCell = line.split("|")[1]?.trim() ?? "";
      if (/^-+$/.test(firstCell)) continue;
      if (/^Entry point\b/.test(firstCell)) {
        inEntryTable = true;
        continue;
      }
      if (!inEntryTable) continue;
      for (const [, method, path] of line.matchAll(PATH)) {
        const segments = path!.split("/").filter(Boolean);
        if (!segments.some((s) => /^[\w.-]+$/.test(s))) continue;
        entries.push({ method: method ?? null, pattern: toPattern(path!) });
      }
    }
  }
  return entries;
}

function toPattern(path: string): RegExp {
  const parts = path.split(/(\{[^}]*\}|:\w+|\*)/);
  const body = parts
    .map((part, i) =>
      part.startsWith("{") || part.startsWith(":")
        ? "[^/]+"
        : part === "*"
          ? i >= parts.length - 2 && !parts.slice(i + 1).join("")
            ? ".*"
            : "[^/]*"
          : part.replace(/[.+?^${}()|[\]\\]/g, "\\$&"),
    )
    .join("");
  return new RegExp(`^${body}$`);
}

/** Routes outside the sign-in that no entry-point row names (each must say who and how). */
export function undocumentedRoutes(routes: RouteRow[], entries: DocumentedEntry[]): string[] {
  return routes
    .filter((r) => !r.signedIn)
    .filter((r) => {
      const path = r.path.replace(/:\w+/g, "x");
      return !entries.some(
        (e) =>
          e.pattern.test(path) &&
          (e.method === null || r.method === "ALL" || e.method === r.method),
      );
    })
    .map((r) => `${r.method} ${r.path}`);
}

