import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  InMemoryCodeEventLog,
  InMemoryCodeHostConnectionStore,
  InMemoryWorkTracker,
} from "@andy/contracts";
import { createApp } from "@andy/api/app";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";
import { format, resolveConfig } from "prettier";

/** Path of the generated client types (ARCHITECTURE §7.5: API client generated from OpenAPI). */
export const GENERATED_PATH = fileURLToPath(new URL("../src/lib/api.gen.ts", import.meta.url));

/**
 * Builds the API's OpenAPI document in-process (no server, no credentials) and renders TS types,
 * formatted so the checked-in file matches byte for byte (the staleness test compares them).
 */
export async function generateApiTypes(): Promise<string> {
  const app = createApp({
    verifier: { verify: () => Promise.reject(new Error("unused")) },
    allowedEmails: new Set(),
    version: "gen",
    webConfig: { firebaseApiKey: "", firebaseAuthDomain: "", projectId: "" },
    tracker: new InMemoryWorkTracker(),
    // Fakes only, so the GitHub setup routes are in the document.
    github: {
      publicUrl: "http://localhost",
      connections: new InMemoryCodeHostConnectionStore(),
      events: new InMemoryCodeEventLog(),
    },
  });
  const doc = (await (await app.request("/openapi.json")).json()) as OpenAPI3;
  const ast = await openapiTS(doc);
  const source = `// Generated by \`pnpm --filter @andy/web gen:api\` from the API's OpenAPI document. Do not edit.\n\n${astToString(ast)}`;
  const options = await resolveConfig(GENERATED_PATH);
  return format(source, { ...options, filepath: GENERATED_PATH });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(GENERATED_PATH, await generateApiTypes());
  console.log(`wrote ${GENERATED_PATH}`);
}
