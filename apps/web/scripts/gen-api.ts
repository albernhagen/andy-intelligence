import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  InMemoryCodeEventLog,
  InMemoryCodeHostConnectionStore,
  InMemoryConfigChangeStore,
  InMemoryDigestSummaryStore,
  InMemoryMilestoneStore,
  InMemoryEpicBreakdownStore,
  InMemoryNightLaunchStore,
  InMemoryRoutingConfigStore,
  InMemoryReleaseNoteStore,
  InMemoryRunStore,
  InMemoryRunnerStore,
  InMemoryWorkTracker,
} from "@andy/contracts";
import { createApp, ownerOnlyAccess } from "@andy/api/app";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";
import { format, resolveConfig } from "prettier";

/** Path of the generated client types (ARCHITECTURE §7.5: API client generated from OpenAPI). */
export const GENERATED_PATH = fileURLToPath(new URL("../src/lib/api.gen.ts", import.meta.url));

/**
 * Builds the API's OpenAPI document in-process (no server, no credentials). The types are not
 * committed (AI-145): `typecheck` generates them first, so they can't be stale or conflict.
 */
export async function apiDocument(): Promise<OpenAPI3> {
  const app = createApp({
    projectAccess: ownerOnlyAccess(),
    verifier: { verify: () => Promise.reject(new Error("unused")) },
    allowedEmails: new Set(),
    version: "gen",
    webConfig: { firebaseApiKey: "", firebaseAuthDomain: "", projectId: "" },
    tracker: new InMemoryWorkTracker(),
    runs: new InMemoryRunStore(),
    runners: new InMemoryRunnerStore(),
    configChanges: new InMemoryConfigChangeStore(),
    nightLaunches: new InMemoryNightLaunchStore(),
    routing: new InMemoryRoutingConfigStore(),
    releaseNotes: new InMemoryReleaseNoteStore(),
    milestones: new InMemoryMilestoneStore(),
    epicBreakdowns: new InMemoryEpicBreakdownStore(),
    digestSummaries: new InMemoryDigestSummaryStore(),
    // Fakes only, so the GitHub setup routes are in the document.
    github: {
      publicUrl: "http://localhost",
      connections: new InMemoryCodeHostConnectionStore(),
      events: new InMemoryCodeEventLog(),
    },
  });
  return (await (await app.request("/openapi.json")).json()) as OpenAPI3;
}

/** Renders the document as TS types, formatted with the repo's prettier config. */
export async function generateApiTypes(): Promise<string> {
  const ast = await openapiTS(await apiDocument());
  const source = `// Generated by \`pnpm --filter @andy/web gen:api\` from the API's OpenAPI document. Do not edit.\n\n${astToString(ast)}`;
  const options = await resolveConfig(GENERATED_PATH);
  return format(source, { ...options, filepath: GENERATED_PATH });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(GENERATED_PATH, await generateApiTypes());
  console.log(`wrote ${GENERATED_PATH}`);
}
